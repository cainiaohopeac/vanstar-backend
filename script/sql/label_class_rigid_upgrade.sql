-- ======================================================================
-- 标签「刚体」标识升级脚本
-- 背景：点云立体框（cuboid）轨迹分两类：
--       刚体（is_rigid=1）—— 同一轨迹(id)的所有帧尺寸全程保持一致，
--             任一关键帧改尺寸自动同步到该轨迹所有帧（关键帧+插值帧）；
--       非刚体（is_rigid=0，默认）—— 各关键帧尺寸独立，需手动「同步尺寸到」。
-- 说明：仅 tool_type 为立体框/框选的类别生效，其它类别忽略该字段。
--       历史轨迹不被追溯修改：只在用户下一次改动尺寸时按刚体规则统一（产品决策 A）。
--       执行一次即可，重复执行会因列已存在而报错（可忽略）。
-- ======================================================================

ALTER TABLE `label_class`
    ADD COLUMN `is_rigid` tinyint(1) DEFAULT 0 COMMENT '刚体标识(仅立体框):1=同轨迹尺寸自动同步一致,0=各帧独立';
