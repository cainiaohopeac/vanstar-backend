-- ======================================================================
-- 标签「立体框内最少点云数」配置升级脚本
-- 背景：点云立体框（cuboid）类别可在「项目详情 - 设置标签」时预设最少点云数，
--       标注下 3D 框后若框内点云数少于该值，则该框自动取消并提示。
-- 说明：
--   min_inside_points 对应立体框（cuboid）拉框时框内点云的最小数量；
--   为 NULL 或 0 表示不限。仅 tool_type 为立体框（cuboid）时生效。
--   执行一次即可，重复执行会因列已存在而报错（可忽略）。
-- ======================================================================

ALTER TABLE `label_class`
    ADD COLUMN `min_inside_points` int DEFAULT NULL COMMENT '立体框内最少点云数(0/NULL=不限)';
