-- ======================================================================
-- 标签「标注工具」配置升级脚本
-- 背景：不同标注标签使用的标注工具不同（图像页：矩形/多边形/画笔；
--       点云/序列页：框选/立体框/折线/关键点/分割等），
--       因此在配置标签时指定标注工具，标注页选中该标签后自动切换到对应工具。
--
-- 说明：
--   tool_type 为 NULL 或空串表示「不限」（兼容存量数据，标注页不强制切换）。
--   执行一次即可，重复执行会因列已存在而报错（可忽略）。
-- ======================================================================

ALTER TABLE `label_class`
    ADD COLUMN `tool_type` varchar(20) DEFAULT NULL COMMENT '标注工具（bbox/polygon/brush/box3d/cuboid/polyline/keypoint/segmentation，空=不限）' AFTER `color`;
